#!/usr/bin/env node
/**
 * gen-vat-backfill — writes the per-product VAT backfill (the VALUES list) into
 * the migration that adds products.vat_rate, from the authoritative rate table
 * docs/vat/crm_products_vat.json (Sigma ERP, 01.10.2026 — see docs/VAT.md).
 *
 *   node scripts/vat/gen-vat-backfill.mjs            rewrite the generated block
 *   node scripts/vat/gen-vat-backfill.mjs --check    exit 1 if the block is stale
 *
 * The block sits between the two marker lines in the migration; nothing else in
 * the file is touched. Offline: it reads two local files and never talks to a
 * database. Rates are taken AS THEY ARE in the table — this script never
 * re-derives a rate (a row someone believes is wrong is changed in the table,
 * with the reason, or later by an owner through products_set_vat_rate()).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const TABLE = join(ROOT, 'docs', 'vat', 'crm_products_vat.json');
export const MIGRATION = join(ROOT, 'supabase', 'migrations', '20260944000900_product_vat_rate.sql');
export const BEGIN = '-- >>> GENERATED by scripts/vat/gen-vat-backfill.mjs from docs/vat/crm_products_vat.json — do not edit by hand';
export const END = '-- <<< END GENERATED';

/** The four Macedonian rates (Sigma Item.VatId 0 / 2 / 3 / 1). */
export const RATES = [0, 0.05, 0.1, 0.18];
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

const lit = (v) => (v == null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

/** One table row → the VALUES tuple (id, rate, source, sigma code, sigma name, evidence). */
export function tuple(r) {
  if (!UUID.test(String(r.id))) throw new Error(`not a product id: ${r.id}`);
  const rate = Number(r.vat_rate);
  if (!RATES.includes(rate)) throw new Error(`${r.id}: rate ${r.vat_rate} is not one of ${RATES.join(', ')}`);
  if (!r.vat_source) throw new Error(`${r.id}: no vat_source`);
  const evidence = r.evidence ? String(r.evidence) : null;
  return `  ('${r.id}'::uuid, ${rate.toFixed(3)}, ${lit(r.vat_source)}, ${lit(r.sigma_code)}, ${lit(r.sigma_name)}, ${lit(evidence)})`;
}

export function buildBlock(rows) {
  const ids = new Set();
  for (const r of rows) {
    if (ids.has(r.id)) throw new Error(`duplicate product id ${r.id}`);
    ids.add(r.id);
  }
  const sorted = [...rows].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  return [BEGIN, `-- ${sorted.length} products`, 'INSERT INTO pg_temp.vat_backfill (id, rate, source, sigma_code, sigma_name, evidence) VALUES',
    sorted.map(tuple).join(',\n') + ';', END].join('\n');
}

export function splice(text, block) {
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < 0 || b < a) throw new Error('migration: generated-block markers not found');
  return text.slice(0, a) + block + text.slice(b + END.length);
}

function main(argv) {
  const rows = JSON.parse(readFileSync(TABLE, 'utf8'));
  const text = readFileSync(MIGRATION, 'utf8');
  const next = splice(text, buildBlock(rows));
  if (argv.includes('--check')) {
    if (next !== text) { console.error('gen-vat-backfill: the migration\'s backfill block is STALE — run node scripts/vat/gen-vat-backfill.mjs'); return 1; }
    console.log(`gen-vat-backfill: up to date (${rows.length} products)`);
    return 0;
  }
  writeFileSync(MIGRATION, next);
  const by = {};
  for (const r of rows) by[r.vat_rate] = (by[r.vat_rate] ?? 0) + 1;
  console.log(`gen-vat-backfill: wrote ${rows.length} products (${Object.entries(by).map(([k, v]) => `${Number(k) * 100} %: ${v}`).join(' · ')})`);
  return 0;
}

if (String(process.argv[1] ?? '').replace(/\\/g, '/').endsWith('vat/gen-vat-backfill.mjs')) {
  process.exitCode = main(process.argv.slice(2));
}
